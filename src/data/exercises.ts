/** 优先取主动肌，用于自动生成收缩说明 */
function autoNote(ex: Exercise): string {
  const primary = ex.muscles.filter((x) => x.role === 'primary')
  const names = primary
    .map((x) => MUSCLE_MAP.get(x.id)?.zh)
    .filter(Boolean)
    .slice(0, 2)
    .join('与')
  return `${names || '目标肌群'}完成「${ex.jointAction}」。向心阶段肌纤维缩短、肌腹隆起，离心阶段被拉长并吸收负荷——控制好离心，才是这个动作真正的增肌部分。`
}

for (const ex of EXERCISES) {
  if (!ex.contractionNote) ex.contractionNote = autoNote(ex)
}

export const EXERCISE_MAP = new Map(EXERCISES.map((e) => [e.id, e]))
